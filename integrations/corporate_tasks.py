"""
Fifty corporate workflows across finance, HR, legal and compliance, IT and
security, sales and marketing, and operations. Each is a separate company
system with its own published tool contract and private ground truth, in the
same strict boundary as companies.py.

About half the systems drift from their published contract the way real
stacks do: an undocumented side effect (`hidden`), a declared effect that is
silently never delivered (`fails`, usually with a slower fallback tool), or an
undocumented reset of an earlier fact (`hidden_del`). Two tasks are
unreachable because the only tool that can deliver a required fact silently
fails. Several contain a trap tool that destroys progress, and most contain a
valid but unnecessary distractor. The planner sees none of the drift; it
learns it from execution and keeps it in the shared graph.

Every task is deterministic, stdlib only, and synthetic.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Callable

from .core import CompanySystem, Tool

F = frozenset


@dataclass(frozen=True)
class CorporateTask:
    id: str
    department: str
    title: str
    builder: Callable[[], CompanySystem]
    goal: frozenset
    drift: str = ""
    reachable: bool = True


def tool(name, pre, add, delete=(), *, risk="low", hidden=(), fails=(), hidden_del=()):
    return Tool(name, F(pre), F(add), F(delete), risk, F(hidden), F(fails), F(hidden_del))


def task(id, department, title, initial, goal, tools, gated=(), drift="", reachable=True):
    def builder(extra_facts=()):
        return CompanySystem(id, set(initial) | set(extra_facts), tools(), human_gated=set(gated))
    return CorporateTask(id, department, title, builder, F(goal), drift, reachable)


def instance(task, case):
    """A fresh system for one case; the case marker is an irrelevant fact the
    model has never seen, so evidence must transfer rather than replay."""
    return task.builder({f"case:{case}"})


